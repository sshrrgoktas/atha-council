'use strict';
// Atha Council -> OpenCode WORK AGENT. Runs only after an owner explicitly approves
// a Task Centre record. Distinct from the retired Council chat participant.
// No OAuth token copied. Ed25519 key is read from the existing paired PC folder.
// The model cannot run shell commands; changes stay in a fresh task-specific clone.
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const crypto=require('node:crypto');
const {spawn}=require('node:child_process');
const DIR=__dirname,CFG=path.join(DIR,'agent-config.json');
const KEY=path.join(DIR,'.council-agent-private.pem');
const STATE=path.join(DIR,'work-agent-state.json');
const PID=path.join(DIR,'work-agent.pid'),STOP=path.join(DIR,'work-agent.stop');
const ROOT=path.join(os.homedir(),'Documents','AthalAI-OpenCode-Work');
const CLI=path.join(os.homedir(),'AppData','Roaming','npm','node_modules','@opencode','cli','bin','opencode.exe');
const BASE='https://atlas-council.sshrrgoktas.workers.dev';
const ALLOWED_REPO='sshrrgoktas/atha-council';
const PERIOD_MS=20000,MODEL='openrouter/nvidia/nemotron-3.5-lightning:free';
const TASK_ID=/^ct_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const EMPTY={lastTick:null,lastError:null,pending:null,lastTask:null};
function readJson(file,fallback){try{return JSON.parse(fs.readFileSync(file,'utf8'))}catch{return fallback}}
function atomic(file,value){const tmp=file+'.tmp-'+process.pid;fs.writeFileSync(tmp,JSON.stringify(value,null,2),{mode:0o600});fs.renameSync(tmp,file)}
function conf(){const c=readJson(CFG,null);return c?.enabled&&c?.agent_id&&c.room_id&&fs.existsSync(KEY)?c:null}
function canonical(method,route,stamp,body){return [method,route,stamp,crypto.createHash('sha256').update(body).digest('base64url')].join('\n')}
async function api(route,body){
 const cfg=conf();if(!cfg)throw Error('WORK_AGENT_UNPAIRED_OR_DISABLED');
 const raw=JSON.stringify(body),stamp=String(Date.now());
 const sig=crypto.sign(null,Buffer.from(canonical('POST',route,stamp,raw)),fs.readFileSync(KEY)).toString('base64url');
 const r=await fetch(BASE+route,{method:'POST',redirect:'error',headers:{
  'content-type':'application/json','x-atha-agent-id':cfg.agent_id,'x-atha-agent-ts':stamp,'x-atha-agent-sig':sig
 },body:raw,signal:AbortSignal.timeout(12000)});
 const data=await r.json().catch(()=>({}));
 if(!r.ok)throw Error('HTTP_'+r.status+'_'+String(data.error||'unknown').slice(0,70));
 return data;
}
function run(program,args,cwd,timeoutMs){
 return new Promise(resolve=>{
  let output='',err='',finished=false;
  const child=spawn(program,args,{cwd,windowsHide:true,stdio:['ignore','pipe','pipe'],shell:false});
  const timer=setTimeout(()=>{try{child.kill()}catch{}},timeoutMs);
  child.stdout.on('data',d=>{if(output.length<200000)output+=d.toString()});
  child.stderr.on('data',d=>{if(err.length<2500)err+=d.toString()});
  child.on('error',e=>{if(!finished){finished=true;clearTimeout(timer);resolve({ok:false,error:String(e.code||e.message).slice(0,90),output,err})}});
  child.on('close',code=>{if(!finished){finished=true;clearTimeout(timer);resolve({ok:code===0,code,output,err})}});
 });
}
function workerConfig(){
 // OpenCode V2 permission rules: no shell/network/subagents, no external paths.
 // A repository is NOT an OS sandbox. Do not run code generated by the model on
 // this Windows host; only git diff --check is performed by this trusted wrapper.
 return {
  $schema:'https://opencode.ai/config.json',
  agents:{'council-worker':{description:'Approved source-only task in isolated Atha Council checkout',mode:'primary',
   permissions:[
    {action:'*',resource:'*',effect:'deny'},
    {action:'read',resource:'*',effect:'allow'},
    {action:'glob',resource:'*',effect:'allow'},
    {action:'grep',resource:'*',effect:'allow'},
    {action:'edit',resource:'*',effect:'allow'},
    {action:'external_directory',resource:'*',effect:'deny'},
    {action:'shell',resource:'*',effect:'deny'},
    {action:'subagent',resource:'*',effect:'deny'},
    {action:'execute',resource:'*',effect:'deny'},
    {action:'websearch',resource:'*',effect:'deny'},
    {action:'webfetch',resource:'*',effect:'deny'},
    {action:'edit',resource:'opencode.json',effect:'deny'},
    {action:'edit',resource:'opencode.jsonc',effect:'deny'},
    {action:'edit',resource:'.opencode/*',effect:'deny'},
    {action:'edit',resource:'.git/*',effect:'deny'},
    {action:'read',resource:'*.env*',effect:'deny'}
   ]
  }}
 };
}
function validPath(v){return typeof v==='string'&&v.length>0&&v.length<=160&&/^[A-Za-z0-9_.\/-]+$/.test(v)&&!v.includes('..')&&!v.startsWith('/')&&!v.startsWith('.git')&&!v.endsWith('opencode.json')&&!v.startsWith('.opencode/')&&!/(?:^|\/)\.env(?:\.|$)|\.(?:pem|key|p12|jks)$/i.test(v)}
async function performTask(task){
 if(!task||!TASK_ID.test(task.id)||task.repo!==ALLOWED_REPO||typeof task.request!=='string'||!task.request.trim())throw Error('INVALID_APPROVED_TASK');
 if(!fs.existsSync(CLI))throw Error('OPENCODE_CLI_NOT_FOUND');
 const baseDir=path.join(ROOT,'tasks');fs.mkdirSync(baseDir,{recursive:true});
 const cwd=path.join(baseDir,task.id);
 if(fs.existsSync(cwd))throw Error('TASK_WORKSPACE_ALREADY_EXISTS'); // Never overwrite or delete prior work.
 const clone=await run('git',['clone','--depth','1','https://github.com/'+ALLOWED_REPO+'.git',cwd],baseDir,90000);
 if(!clone.ok)throw Error('GIT_CLONE_FAILED');
 const workBranch='work/'+task.id;
 const branch=await run('git',['switch','-c',workBranch],cwd,15000);
 if(!branch.ok)throw Error('GIT_BRANCH_FAILED');
 fs.writeFileSync(path.join(cwd,'opencode.json'),JSON.stringify(workerConfig(),null,2),{flag:'wx'});
 const prompt=[
  'Yalnızca BU çalışma kopyasında aşağıdaki kullanıcı-onaylı göreve ait kaynak dosyaları düzenle.',
  'Terminal/shell/web/harici dosya ve cihaz kullanma, sır veya token okuma.',
  'Bu çalışma kopyası dışına yazma. YAPMA: yayın, push, merge, paket indirme, program çalıştırma veya test yürütme.',
  'Görev başarısı için uygulanmış gerçek dosya farkı gerekir. Sadece plan yazma.',
  'Kullanıcı onaylı iş emri '+task.id+': '+task.request.slice(0,2000),
  'Yapamadığın şeyi yaptım deme. İş bitince en fazla iki cümleyle hangi kodu değiştirdiğini özetle.'
 ].join('\n');
 const result=await run(CLI,['run','--standalone','--agent','council-worker','--model',MODEL,'--format','json',prompt],cwd,180000);
 const status=await run('git',['status','--porcelain','--untracked-files=all'],cwd,16000);
 if(!status.ok)throw Error('GIT_STATUS_FAILED');
 const changed=status.output.split(/\r?\n/).filter(Boolean).map(x=>x.slice(3).replace(/^"|"$/g,'')).filter(x=>x!=='opencode.json');
 if(!changed.length)throw Error(result.ok?'NO_SOURCE_CHANGES':'MODEL_FAILED_NO_SOURCE_CHANGES');
 if(changed.length>30||changed.some(x=>!validPath(x)))throw Error('UNSAFE_CHANGED_PATH');
 const diff=await run('git',['diff','--check'],cwd,16000);
 if(!diff.ok)throw Error('DIFF_CHECK_FAILED');
 // Never claim that tests ran: executing model-authored code on the host is unsafe.
 const summary='OpenCode ayrı çalışma kopyasında '+changed.length+' dosya değiştirdi. Git diff --check geçti; kod testleri çalıştırılmadı. Çıktı kullanıcı incelemesinde.';
 return {room_id:conf().room_id,task_id:task.id,outcome:'review',summary,files:changed,checks:['git diff --check: geçti','Kod testleri: çalıştırılmadı','Push/merge/yayın: yapılmadı'],branch:workBranch};
}
async function processOnce(){
 const config=conf();if(!config)throw Error('NOT_PAIRED_OR_DISABLED');
 const state=readJson(STATE,{...EMPTY});state.lastTick=Date.now();
 if(state.pending){
  const result=await api('/api/atha-opencode/work-result',state.pending);
  if(!result.saved)throw Error('RESULT_NOT_SAVED');
  state.lastTask=state.pending.task_id;state.pending=null;state.lastError=null;atomic(STATE,state);
 }
 const poll=await api('/api/atha-opencode/work-poll',{room_id:config.room_id});
 if(poll.paused||!poll.tasks?.length){state.lastError=null;atomic(STATE,state);return {claimed:0,paused:!!poll.paused}}
 const task=poll.tasks[0];let report;
 try{report=await performTask(task)}catch(e){
  report={room_id:config.room_id,task_id:task.id,outcome:'failed',summary:'OpenCode işi tamamlayamadı: '+String(e.message||e).slice(0,120)+'. Otomatik tekrar yapılmadı.',files:[],checks:['Test: çalıştırılmadı'],branch:'work/'+task.id};
 }
 state.pending=report;atomic(STATE,state);
 const saved=await api('/api/atha-opencode/work-result',report);
 if(!saved.saved)throw Error('RESULT_SAVE_FAILED');
 state.lastTask=task.id;state.pending=null;state.lastError=null;state.lastTick=Date.now();atomic(STATE,state);
 return {claimed:1,taskId:task.id,outcome:report.outcome};
}
function isRunning(){let n=Number(fs.existsSync(PID)?fs.readFileSync(PID,'utf8'):0);if(!Number.isSafeInteger(n)||n<1)return false;try{process.kill(n,0);return true}catch{return false}}
function status(){const c=readJson(CFG,null),s=readJson(STATE,{...EMPTY});return {configured:!!c&&fs.existsSync(KEY),enabled:!!c?.enabled,running:isRunning(),room_id:c?.room_id||null,last_tick:s.lastTick,last_error:s.lastError,last_task:s.lastTask,pending_result:!!s.pending,repo:ALLOWED_REPO,safe_work_mode:true}}
async function daemon(){
 if(isRunning())return;
 fs.rmSync(STOP,{force:true});fs.writeFileSync(PID,String(process.pid));
 try{for(;;){
  if(fs.existsSync(STOP)||!conf())break;
  try{await processOnce()}catch(e){const s=readJson(STATE,{...EMPTY});s.lastError=String(e.message||e).slice(0,120);s.lastTick=Date.now();atomic(STATE,s);if(/HTTP_401|HTTP_403/.test(s.lastError))break}
  await new Promise(resolve=>setTimeout(resolve,PERIOD_MS));
 }}finally{fs.rmSync(PID,{force:true});fs.rmSync(STOP,{force:true})}
}
function start(){
 if(isRunning())return {started:false,reason:'ALREADY_RUNNING'};
 if(!conf())throw Error('PAIRING_REQUIRED');
 fs.rmSync(STOP,{force:true});
 const child=spawn(process.execPath,[__filename,'daemon'],{cwd:DIR,detached:true,windowsHide:true,stdio:'ignore'});
 child.unref();return {started:true,pid:child.pid};
}
async function main(){const cmd=process.argv[2]||'status';
 if(cmd==='status')console.log(JSON.stringify(status()));
 else if(cmd==='once')console.log(JSON.stringify(await processOnce()));
 else if(cmd==='start')console.log(JSON.stringify(start()));
 else if(cmd==='stop'){fs.writeFileSync(STOP,'1');console.log(JSON.stringify({requested:true,running:isRunning()}))}
 else if(cmd==='daemon')await daemon();
 else throw Error('Expected status, once, start, stop');
}
if(require.main===module)main().catch(e=>{console.error('OpenCode work agent: '+e.message);process.exitCode=1});
module.exports={canonical,workerConfig,validPath,status,performTask};
